// Fixed feasts that move to Easter Monday when they fall on or before Easter Sunday
const MOVES_TO_EASTER_MONDAY = new Set([key(4, 23), key(4, 25)])

/** Names celebrating on a given day (year matters for the movable feasts). */
export function namesOn(date: Date): string[] {
  const year = date.getFullYear()
  const easter = orthodoxEaster(year)
  const diff = Math.round((new Date(year, date.getMonth(), date.getDate()).getTime() - easter.getTime()) / 86_400_000)
  const k = key(date.getMonth() + 1, date.getDate())
  const out: string[] = []

  // a fixed feast that would fall before/on Easter is celebrated on Easter Monday
  if (MOVES_TO_EASTER_MONDAY.has(k)) {
    if (!(date <= easter)) out.push(...(FIXED[k] ?? []))
  } else {
    out.push(...(FIXED[k] ?? []))
  }
  if (diff === 1) {
    for (const moved of MOVES_TO_EASTER_MONDAY) {
      const [m, d] = moved.split('-').map(Number)
      if (new Date(year, m - 1, d) <= easter) out.push(...(FIXED[moved] ?? []))
    }
  }

  if (diff === -7) out.push('Βάιος', 'Βάια')
  if (diff === 0) out.push('Αναστάσιος', 'Αναστασία', 'Λάμπρος', 'Λαμπρινή')
  if (diff === 5) out.push('Πηγή', 'Ζωοδόχος')
  if (diff === 7) out.push('Θωμάς')
  if (diff === 49) out.push('Τριάδα')
  return [...new Set(out)]
}
